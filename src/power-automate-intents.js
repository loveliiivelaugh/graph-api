function normalizeIntent(intent) {
  return String(intent || "").trim();
}

function lower(value) {
  return normalizeIntent(value).toLowerCase();
}

function includesAny(text, values) {
  return values.some((value) => text.includes(value));
}

function uniqueByJson(items) {
  const seen = new Set();
  return items.filter((item) => {
    const key = JSON.stringify(item);
    if (seen.has(key)) {
      return false;
    }

    seen.add(key);
    return true;
  });
}

function detectTrigger(text) {
  if (includesAny(text, ["email", "mailbox", "inbox", "outlook"])) {
    return {
      type: "outlook.email.received",
      confidence: 0.9
    };
  }

  if (includesAny(text, ["form", "forms", "submission", "submitted"])) {
    return {
      type: "forms.response.submitted",
      confidence: 0.85
    };
  }

  if (includesAny(text, ["schedule", "daily", "every day", "weekly", "every week", "every morning"])) {
    return {
      type: "recurrence",
      confidence: 0.8
    };
  }

  if (includesAny(text, ["teams message", "teams alert", "incident", "ticket"])) {
    return {
      type: "manual.or.external.event",
      confidence: 0.45
    };
  }

  return {
    type: "recurrence",
    confidence: 0.35
  };
}

function detectActions(text) {
  const actions = [];

  if (includesAny(text, ["summarize", "summary", "digest"])) {
    actions.push({ type: "summarize" });
  }

  if (includesAny(text, ["teams", "channel", "post it to teams", "send to teams", "alert"])) {
    actions.push({ type: "teams.postMessage" });
  }

  if (includesAny(text, ["planner", "task", "todo"])) {
    actions.push({ type: "planner.createTask" });
  }

  if (includesAny(text, ["approval", "approve", "review request"])) {
    actions.push({ type: "approvals.createApproval" });
  }

  if (includesAny(text, ["route", "forward", "send email"])) {
    actions.push({ type: "outlook.sendEmail" });
  }

  if (actions.length === 0) {
    actions.push({ type: "compose" });
  }

  return uniqueByJson(actions);
}

function detectConnectors(trigger, actions) {
  const connectors = [];

  if (trigger.type.startsWith("outlook.")) {
    connectors.push("Office 365 Outlook");
  }

  if (trigger.type.startsWith("forms.")) {
    connectors.push("Microsoft Forms");
  }

  for (const action of actions) {
    if (action.type === "teams.postMessage") {
      connectors.push("Microsoft Teams");
    }

    if (action.type === "planner.createTask") {
      connectors.push("Planner");
    }

    if (action.type === "approvals.createApproval") {
      connectors.push("Approvals");
    }

    if (action.type === "outlook.sendEmail") {
      connectors.push("Office 365 Outlook");
    }
  }

  return [...new Set(connectors)];
}

function detectQuestions(text, trigger, actions) {
  const questions = [];

  if (trigger.type === "outlook.email.received") {
    questions.push("Which mailbox should be monitored?");
  }

  if (actions.some((item) => item.type === "teams.postMessage")) {
    questions.push("Which Teams channel or chat should receive alerts?");
  }

  if (actions.some((item) => item.type === "planner.createTask")) {
    questions.push("Which Planner plan or bucket should receive new tasks?");
  }

  if (actions.some((item) => item.type === "approvals.createApproval")) {
    questions.push("Who should be the approver for this workflow?");
  }

  if (trigger.type === "recurrence") {
    questions.push("What schedule should this run on?");
  }

  if (includesAny(text, ["vip", "important sender", "priority sender"])) {
    questions.push("How should VIP senders be defined?");
  }

  return [...new Set(questions)].slice(0, 3);
}

function selectTemplate(trigger, actions) {
  if (actions.some((item) => item.type === "teams.postMessage")) {
    return "teams-alert";
  }

  if (actions.some((item) => item.type === "approvals.createApproval")) {
    return "approval";
  }

  if (trigger.type === "recurrence") {
    return "scheduled-basic";
  }

  return "scheduled-basic";
}

function summarizeIntent(text, trigger, actions, requiredConnectors, openQuestions, templateId) {
  return {
    intent: text,
    recommendedTrigger: {
      type: trigger.type,
      confidence: trigger.confidence
    },
    recommendedActions: actions,
    requiredConnectors,
    openQuestions,
    draftTemplate: templateId
  };
}

function buildTemplateParams(intentPlan) {
  const text = lower(intentPlan.intent);
  const baseName = intentPlan.intent.slice(0, 80) || "Generated flow";

  if (intentPlan.draftTemplate === "teams-alert") {
    return {
      name: baseName,
      channel: "<channel-id>",
      summary: includesAny(text, ["incident", "alert"]) ? "New alert generated by automation" : "Automated Teams message"
    };
  }

  if (intentPlan.draftTemplate === "approval") {
    return {
      name: baseName,
      approver: "<approver@contoso.com>",
      title: baseName,
      details: "Review this generated approval flow."
    };
  }

  return {
    name: baseName,
    schedule: "0 9 * * *",
    message: "Scheduled automation executed"
  };
}

export function buildIntentPlan(intent) {
  const normalizedIntent = normalizeIntent(intent);

  if (!normalizedIntent) {
    throw new Error("Provide a non-empty intent string.");
  }

  const text = lower(normalizedIntent);
  const trigger = detectTrigger(text);
  const actions = detectActions(text);
  const requiredConnectors = detectConnectors(trigger, actions);
  const openQuestions = detectQuestions(text, trigger, actions);
  const draftTemplate = selectTemplate(trigger, actions);

  return summarizeIntent(
    normalizedIntent,
    trigger,
    actions,
    requiredConnectors,
    openQuestions,
    draftTemplate
  );
}

export function buildIntentQuestions(intent) {
  const plan = buildIntentPlan(intent);
  return {
    intent: plan.intent,
    questions: plan.openQuestions
  };
}

export function buildScaffoldInput(intentPlan) {
  if (!intentPlan || typeof intentPlan !== "object") {
    throw new Error("Provide a valid intent plan JSON object.");
  }

  if (!intentPlan.intent || !intentPlan.draftTemplate) {
    throw new Error("Intent JSON must include at least `intent` and `draftTemplate`.");
  }

  return {
    templateId: intentPlan.draftTemplate,
    params: buildTemplateParams(intentPlan)
  };
}
